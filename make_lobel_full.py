FONT = 'Arial'
SIZE = Pt(11)

def p(text='', bold=False, italic=False, size=None, align=None, color=None, sb=0, sa=4):
    par = doc.add_paragraph()
    par.paragraph_format.space_before = Pt(sb)
    par.paragraph_format.space_after  = Pt(sa)
    if align:
        par.alignment = align
    if text:
        run = par.add_run(text)
        run.bold = bold; run.italic = italic
        run.font.name = FONT; run.font.size = size or SIZE
        if color:
            run.font.color.rgb = RGBColor(*color)
    return par

def highlight_para(text, bg='F4B942'):
    par = doc.add_paragraph()
    par.paragraph_format.space_before = Pt(10)
    par.paragraph_format.space_after  = Pt(4)
    run = par.add_run(text)
    run.bold = True; run.italic = True
    run.font.name = FONT; run.font.size = SIZE
    rPr = run._r.get_or_add_rPr()
    shd = OxmlElement('w:shd')
    shd.set(qn('w:val'), 'clear')
    shd.set(qn('w:color'), 'auto')
    shd.set(qn('w:fill'), bg)
    rPr.append(shd)
    return par

def sys_title(text):
    par = doc.add_paragraph()
    par.paragraph_format.space_before = Pt(10)
    par.paragraph_format.space_after  = Pt(2)
    run = par.add_run(text.upper())
    run.bold = True; run.font.name = FONT; run.font.size = SIZE
    return par

def bullet(bold_part, normal_part='', italic_part=''):
    try:
        par = doc.add_paragraph(style='List Bullet')
    except Exception:
        par = doc.add_paragraph()
        par.paragraph_format.left_indent = Pt(18)
    par.paragraph_format.space_before = Pt(0)
    par.paragraph_format.space_after  = Pt(3)
    if bold_part:
        r = par.add_run(bold_part); r.bold = True
        r.font.name = FONT; r.font.size = SIZE
    if normal_part:
        r = par.add_run(normal_part)
        r.font.name = FONT; r.font.size = SIZE
    if italic_part:
        r = par.add_run(italic_part); r.italic = True
        r.font.name = FONT; r.font.size = SIZE
    return par

def note(text):
    par = doc.add_paragraph()
    par.paragraph_format.left_indent  = Pt(24)
    par.paragraph_format.space_before = Pt(0)
    par.paragraph_format.space_after  = Pt(3)
    run = par.add_run(text); run.italic = True
    run.font.name = FONT; run.font.size = SIZE
    return par

def divider():
    par = doc.add_paragraph()
    par.paragraph_format.space_before = Pt(4)
    par.paragraph_format.space_after  = Pt(4)
    pPr = par._p.get_or_add_pPr()
    pBdr = OxmlElement('w:pBdr')
    bot = OxmlElement('w:bottom')
    bot.set(qn('w:val'), 'single'); bot.set(qn('w:sz'), '4')
    bot.set(qn('w:space'), '1'); bot.set(qn('w:color'), 'AAAAAA')
    pBdr.append(bot); pPr.append(pBdr)

