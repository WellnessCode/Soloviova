def para(text='', bold=False, italic=False, size=11, align=None, color=None, space_before=0, space_after=4):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(space_before)
    p.paragraph_format.space_after  = Pt(space_after)
    if align:
        p.alignment = align
    if text:
        run = p.add_run(text)
        run.bold = bold
        run.italic = italic
        run.font.size = Pt(size)
        run.font.name = 'Arial'
        if color:
            run.font.color.rgb = RGBColor(*color)
    return p

def highlight_heading(text, hex_color='F4B942'):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(10)
    p.paragraph_format.space_after  = Pt(6)
    run = p.add_run(text)
    run.bold = True
    run.italic = True
    run.font.size = Pt(11)
    run.font.name = 'Arial'
    rPr = run._r.get_or_add_rPr()
    shd = OxmlElement('w:shd')
    shd.set(qn('w:val'), 'clear')
    shd.set(qn('w:color'), 'auto')
    shd.set(qn('w:fill'), hex_color)
    rPr.append(shd)
    return p

def sys_title(text):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(10)
    p.paragraph_format.space_after  = Pt(3)
    run = p.add_run(text.upper())
    run.bold = True
    run.font.size = Pt(11)
    run.font.name = 'Arial'
    return p

def bullet(text, bold_part='', normal_part=''):
    p = doc.add_paragraph(style='List Bullet')
    p.paragraph_format.space_before = Pt(0)
    p.paragraph_format.space_after  = Pt(3)
    if bold_part:
        r1 = p.add_run(bold_part)
        r1.bold = True
        r1.font.size = Pt(11)
        r1.font.name = 'Arial'
        if normal_part:
            r2 = p.add_run(normal_part)
            r2.font.size = Pt(11)
            r2.font.name = 'Arial'
    else:
        r = p.add_run(text)
        r.font.size = Pt(11)
        r.font.name = 'Arial'
    return p

